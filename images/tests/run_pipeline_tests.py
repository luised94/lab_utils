r"""
Regression harness for the data-side gel densitometry scripts. Reads as the
pipeline's handoff contract: for each script, in pipeline order, it states the
inputs that must already exist, the command to run, the outputs that must appear,
the checks JSON that must carry no failed hard check, and the few named golden
values that must not move silently. Nothing here imports pipeline code; every
stage is driven through its command line and observed only through the files it
leaves and its exit code, exactly as the stages hand off to each other in
production. That is deliberate: it is what lets a script be renamed, split, or
reorganized without rewriting the test, and it is what makes a red result mean
"a handoff or a number changed", never "the harness reached inside and broke".

How this is meant to be used (it is a signal, not a gate): run it before stepping
away and after coming back or finishing a reorganization. A red result has exactly
two honest resolutions and no third. Either the pipeline regressed, and you fix it;
or you changed a contract on purpose, and you re-bless it with --update and record
why in the commit. The illegal move is silencing an assertion without a note; the
first time that happens the harness starts to lie. --update never runs by default,
prints every value it (re)captures with a diff against the prior golden, and
refuses to capture a value that is not reproducible across two back-to-back runs,
so re-blessing is always a visible, deliberate act rather than a green button.

Three artifacts, three different lifecycles:
  tests/fixtures/            hand-authored seed inputs. NEVER regenerated by this
                             harness; --update does not touch them. They change
                             only when you edit them by hand, deliberately.
  tests/golden_values.json   captured numbers, keyed by (step, named cell). Written
                             on the first --update run, re-blessed by later --update
                             runs. Carries a hash of the seed fixtures it was
                             captured against, so a fixture edit is diagnosed by its
                             cause ("fixtures changed since goldens captured") rather
                             than as a scatter of value mismatches.
  this file                  the contract. One block per stage; a reorganization of
                             any stage is an edit to that one block.

The serve stage is exercised with NO --tiff and no sibling .tif beside the fixture,
which is the no-crop path: the server serves, POST /extract shells the same
extract_lane_values.py the command line uses, and the written CSV is compared to the
command-line region run. No image is read anywhere in this harness.

Stdlib only. Flat and procedural; emit_message / die / record_check are the only
helpers, duplicated verbatim into each script per the house convention.

Run:
    python3 tests/run_pipeline_tests.py                 (check against goldens)
    python3 tests/run_pipeline_tests.py --update        (re-capture goldens)
"""

