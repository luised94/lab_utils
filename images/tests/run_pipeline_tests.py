# -----------------------------------------------------------------------------
# STEP 8: serve_gel_picker, no-crop path. Launch with NO --tiff and no sibling
# .tif, so the server serves without reading any image; POST /extract runs the same
# extract_lane_values.py the command line uses; assert the server-written CSV's
# per-lane values equal the command-line region run (STEP 3). Clean teardown via
# POST /shutdown; the process is joined with a timeout and only killed as a last
# resort, so a failure cannot leave a zombie or hang the harness.
# Reorganizing serve (region-picker changes, payload/html changes) touches its
# request shape here, but the CLI-equivalence assertion is unchanged as long as
# /extract still shells the extractor.
# -----------------------------------------------------------------------------
step_name = "serve_gel_picker"
serve_process = None
serve_detail = "contract ok"
serve_passed = True
try:
    # Claim a port from a small range in case the base port is momentarily busy.
    serve_port = None
    for candidate_port in range(SERVE_BASE_PORT, SERVE_BASE_PORT + SERVE_PORT_RETRY_COUNT):
        serve_command = [
            STAGE_INTERPRETER,
            str(REPOSITORY_ROOT_DIRECTORY / "serve_gel_picker.py"),
            str(working_gel_directory),
            "--port",
            str(candidate_port),
        ]
        serve_process = subprocess.Popen(
            serve_command, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
        )
        server_base_url = "http://127.0.0.1:%d" % candidate_port
        server_became_ready = False
        for _poll_attempt in range(SERVE_READINESS_POLL_COUNT):
            if serve_process.poll() is not None:
                # The server exited before becoming ready (likely port in use);
                # break to try the next candidate port.
                break
            try:
                with urllib.request.urlopen(
                    server_base_url + "/payload", timeout=1
                ) as readiness_response:
                    if readiness_response.status == 200:
                        server_became_ready = True
                        break
            except Exception:
                time.sleep(SERVE_READINESS_POLL_SECONDS)
        if server_became_ready:
            serve_port = candidate_port
            break
        # This candidate port did not come up; ensure the process is gone before
        # trying the next one, so we never leak a half-started server.
        if serve_process.poll() is None:
            serve_process.terminate()
        serve_process.wait(timeout=SERVE_SHUTDOWN_JOIN_SECONDS)
        serve_process = None

    if serve_port is None:
        serve_passed, serve_detail = False, "server did not become ready on any port"
    else:
        # POST the same region selection STEP 3 ran on the command line.
        extract_request_body = json.dumps(
            {
                "mode": "region",
                "start_millimetres": REGION_START_MILLIMETRES,
                "end_millimetres": REGION_END_MILLIMETRES,
                "net_baseline": REGION_NET_BASELINE,
            }
        ).encode("utf-8")
        extract_request = urllib.request.Request(
            server_base_url + "/extract",
            data=extract_request_body,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(
            extract_request, timeout=SERVE_REQUEST_TIMEOUT_SECONDS
        ) as extract_response:
            extract_result = json.loads(extract_response.read())
        if not extract_result.get("ok"):
            serve_passed, serve_detail = False, "server /extract failed: " + str(
                extract_result.get("error")
            )
        else:
            # Compare the server's returned rows to the command-line region CSV on
            # the per-lane value, the number the pipeline reports. Provenance
            # columns (timestamps etc) are not compared.
            command_line_values_by_lane = {}
            with extract_region_csv_path.open(
                newline="", encoding="utf-8-sig"
            ) as command_line_handle:
                for command_line_row in csv.DictReader(command_line_handle):
                    command_line_values_by_lane[int(command_line_row["lane_index"])] = (
                        command_line_row["value"].strip()
                    )
            server_values_by_lane = {}
            for server_row in extract_result.get("rows", []):
                server_values_by_lane[int(server_row["lane_index"])] = str(
                    server_row["value"]
                ).strip()
            mismatched_lanes = [
                lane_index
                for lane_index in command_line_values_by_lane
                if command_line_values_by_lane[lane_index]
                != server_values_by_lane.get(lane_index)
            ]
            if mismatched_lanes:
                serve_passed, serve_detail = False, "serve vs CLI mismatch at lanes %s" % (
                    mismatched_lanes[:5]
                )
            else:
                serve_detail = "serve /extract equals CLI over %d lanes" % len(
                    command_line_values_by_lane
                )
        # Clean teardown regardless of the assertion outcome above.
        try:
            urllib.request.urlopen(
                urllib.request.Request(
                    server_base_url + "/shutdown", data=b"{}", method="POST"
                ),
                timeout=SERVE_REQUEST_TIMEOUT_SECONDS,
            ).read()
        except Exception:
            pass
finally:
    if serve_process is not None:
        try:
            serve_process.wait(timeout=SERVE_SHUTDOWN_JOIN_SECONDS)
        except subprocess.TimeoutExpired:
            serve_process.kill()
            serve_process.wait(timeout=SERVE_SHUTDOWN_JOIN_SECONDS)
register_step_outcome(step_name, serve_passed, serve_detail)

