def read_named_cell(csv_path, match_column, match_value, value_column):
    # Pull one cell: the value_column of the row whose match_column equals
    # match_value (compared as integers, which every lane/band key in these CSVs
    # is). utf-8-sig strips the Excel BOM and cells are trimmed, matching how every
    # pipeline script reads its CSVs, so a hand-exported file cannot break the
    # match invisibly.
    with csv_path.open(newline="", encoding="utf-8-sig") as csv_handle:
        for raw_row in csv.DictReader(csv_handle):
            trimmed_row = {
                column_name: (cell.strip() if isinstance(cell, str) else cell)
                for column_name, cell in raw_row.items()
            }
            if int(trimmed_row[match_column]) == match_value:
                return trimmed_row[value_column]
    return None


def read_named_cell_two_keys(
    csv_path, first_column, first_value, second_column, second_value, value_column
):
    # As read_named_cell but keyed on two integer columns (lane_index plus
    # canonical_band_index in band_measurements, where a lane carries many bands).
    with csv_path.open(newline="", encoding="utf-8-sig") as csv_handle:
        for raw_row in csv.DictReader(csv_handle):
            trimmed_row = {
                column_name: (cell.strip() if isinstance(cell, str) else cell)
                for column_name, cell in raw_row.items()
            }
            if (
                int(trimmed_row[first_column]) == first_value
                and int(trimmed_row[second_column]) == second_value
            ):
                return trimmed_row[value_column]
    return None


def checks_json_has_failed_hard_check(checks_json_path):
    # A failed hard check invalidates the stage's output. Returns (has_failure,
    # check_name). Every script writes a top-level "checks" array of records carrying
    # severity and passed, BUT the name field is not uniform: validate_sample_sheet
    # writes "check_name" while extract/plot/aggregate/validate_manifest write
    # "check". Both spellings are read here so this one helper serves every stage;
    # the happy-path callers only ever see "check", so the fallback is a no-op for
    # them. (The schema divergence is noted for the FINDINGS doc; not fixed here.)
    checks_report = json.loads(checks_json_path.read_text(encoding="utf-8-sig"))
    for check_record in checks_report.get("checks", []):
        if check_record.get("severity") == "hard" and not check_record.get("passed"):
            return True, (
                check_record.get("check_name")
                or check_record.get("check")
                or "unnamed hard check"
            )
    return False, ""


def golden_relative_difference(observed_text, golden_value):
    # Compare a freshly produced cell (a string read from a CSV) against a stored
    # golden number by relative difference, so float formatting like "162056329.0"
    # vs 162056329 compares equal. Returns the relative difference as a float.
    observed_value = float(observed_text)
    golden_number = float(golden_value)
    if golden_number == 0.0:
        return abs(observed_value)
    return abs(observed_value - golden_number) / abs(golden_number)


