def evaluate_golden(step_name, golden_key, observed_text):
    # Compare-or-capture one golden. In --update mode, capture the observed value and
    # print a diff versus the prior value so a re-bless is always visible. In compare
    # mode, measure the relative difference against the stored golden and return
    # whether it is within tolerance, with a detail string for the outcome line.
    #
    # Goldens are only ever placed on cells that are deterministic functions of the
    # seed input (integer signal sums, blank-corrected values, group means), never on
    # provenance fields such as gel_id (which is derived from the directory name) or
    # the generated_at timestamps, so a captured value is reproducible run to run.
    # This was verified directly while building the harness: numeric outputs of
    # analyze_gel were byte-identical across independent runs. A per-update
    # double-run guard was considered and rejected as defense the evidence does not
    # require; if a future golden is placed on a noisier cell, run --update twice and
    # confirm the captured value is stable before trusting it.
    fully_qualified_key = step_name + "." + golden_key
    tolerance = GOLDEN_RELATIVE_TOLERANCE_OVERRIDES.get(
        fully_qualified_key, DEFAULT_RELATIVE_TOLERANCE
    )
    if updating_goldens:
        captured_goldens.setdefault(step_name, {})[golden_key] = observed_text
        prior_value = prior_goldens.get(step_name, {}).get(golden_key)
        if prior_value is None:
            emit_message(
                "golden", "capture " + fully_qualified_key + " = " + str(observed_text)
            )
        elif str(prior_value) != str(observed_text):
            relative_difference = golden_relative_difference(observed_text, prior_value)
            emit_message(
                "golden",
                "re-bless "
                + fully_qualified_key
                + ": "
                + str(prior_value)
                + " -> "
                + str(observed_text)
                + " (rel %.3e)" % relative_difference,
            )
        return True, "captured"
    golden_value = stored_goldens.get(step_name, {}).get(golden_key)
    if golden_value is None:
        return False, "golden " + fully_qualified_key + " absent; run --update"
    relative_difference = golden_relative_difference(observed_text, golden_value)
    within_tolerance = relative_difference <= tolerance
    detail_text = "%s: %s vs golden %s (rel %.3e, tol %.0e)" % (
        golden_key,
        observed_text,
        golden_value,
        relative_difference,
        tolerance,
    )
    return within_tolerance, detail_text


def run_stage_and_assert_contract(
    step_name,
    stage_command,
    required_input_files,
    expected_output_files,
    checks_json_file,
):
    # Assert one stage's boundary contract, in the order a failure is most cheaply
    # diagnosed: prerequisites (is the stage wired to inputs that exist), exit code,
    # products (did it leave what the next stage needs), and the hard-check gate.
    # Returns (contract_passed, detail_text) so the caller can then layer on the
    # stage's golden-value checks. Prerequisite failures are tagged distinctly from
    # product failures because they mean different things: a missing prerequisite is
    # usually a fixture or wiring problem, a missing product is a stage regression.
    for required_input_file in required_input_files:
        if not required_input_file.is_file():
            return False, "prerequisite missing: " + required_input_file.name
    completed_process = subprocess.run(stage_command, capture_output=True, text=True)
    if completed_process.returncode != 0:
        last_stderr_line = ""
        if completed_process.stderr.strip():
            last_stderr_line = completed_process.stderr.strip().splitlines()[-1]
        return False, "exit %d: %s" % (completed_process.returncode, last_stderr_line)
    for expected_output_file in expected_output_files:
        if not expected_output_file.is_file():
            return False, "product missing: " + expected_output_file.name
    if checks_json_file is not None:
        has_hard_failure, failed_check_name = checks_json_has_failed_hard_check(
            checks_json_file
        )
        if has_hard_failure:
            return False, "failed hard check: " + failed_check_name
    return True, "contract ok"


def run_stage_and_assert_named_hard_check(
    step_name, stage_command, expected_check_name, checks_json_file
):
    # The inverse of run_stage_and_assert_contract: assert a stage that SHOULD fail
    # does fail, at the SPECIFIC gate we mean. This is what proves the gates gate.
    # A bare "nonzero exit" assertion is not enough: an unrelated crash (a typo in the
    # fixture, a missing file, a different check firing first) also exits nonzero and
    # would masquerade as the gate working. So this asserts BOTH that the exit is
    # nonzero AND that the named hard check is the one that failed in the checks JSON.
    # Returns (passed, detail_text) with the same self-triaging detail style as the
    # happy-path steps. The checks JSON is required: a stage that dies before writing
    # it (e.g. an argparse-level rejection) is a DIFFERENT failure than the gate we
    # are testing, and is reported as such rather than counted as a pass.
    completed_process = subprocess.run(stage_command, capture_output=True, text=True)
    if completed_process.returncode == 0:
        return False, "expected nonzero exit but stage succeeded"
    if not checks_json_file.is_file():
        last_stderr_line = ""
        if completed_process.stderr.strip():
            last_stderr_line = completed_process.stderr.strip().splitlines()[-1]
        return False, (
            "exited nonzero but wrote no checks JSON (%s); expected hard check %r. "
            "last stderr: %s"
            % (checks_json_file.name, expected_check_name, last_stderr_line)
        )
    has_hard_failure, failed_check_name = checks_json_has_failed_hard_check(
        checks_json_file
    )
    if not has_hard_failure:
        return False, (
            "exited nonzero but no hard check failed in %s; expected %r"
            % (checks_json_file.name, expected_check_name)
        )
    if failed_check_name != expected_check_name:
        return False, (
            "wrong gate fired: got %r, expected %r"
            % (failed_check_name, expected_check_name)
        )
    return True, "gated on %r as expected" % expected_check_name


def register_step_outcome(step_name, passed, detail_text):
    # One line per step to stderr, self-triaging: the detail says whether a failure
    # was a wiring break (prerequisite/product/exit) or a numbers change (golden),
    # so the reader knows how to respond without opening the code.
    global any_step_failed
    verdict = "PASS" if passed else "FAIL"
    outcome_line = "%-4s %-22s %s" % (verdict, step_name, detail_text)
    step_outcome_lines.append((step_name, passed, outcome_line))
    emit_message("step", outcome_line)
    if not passed:
        any_step_failed = True


