def read_named_cell(csv_path, match_column, match_value, value_column):
    # Pull one cell: the value_column of the row whose match_column equals
    # match_value (compared as integers, which every lane/band key in these CSVs
    # is). utf-8-sig strips the Excel BOM and cells are trimmed, matching how every
    # pipeline script reads its CSVs, so a hand-exported file cannot break the
    # match invisibly.
    with csv_path.open(newline="", encoding="utf-8-sig") as csv_handle:
        for raw_row in csv.DictReader(csv_handle):
            trimmed_row = {
                column_name: (cell.strip() if isinstance(cell, str) else cell)
                for column_name, cell in raw_row.items()
            }
            if int(trimmed_row[match_column]) == match_value:
                return trimmed_row[value_column]
    return None


def read_named_cell_two_keys(
    csv_path, first_column, first_value, second_column, second_value, value_column
):
    # As read_named_cell but keyed on two integer columns (lane_index plus
    # canonical_band_index in band_measurements, where a lane carries many bands).
    with csv_path.open(newline="", encoding="utf-8-sig") as csv_handle:
        for raw_row in csv.DictReader(csv_handle):
            trimmed_row = {
                column_name: (cell.strip() if isinstance(cell, str) else cell)
                for column_name, cell in raw_row.items()
            }
            if (
                int(trimmed_row[first_column]) == first_value
                and int(trimmed_row[second_column]) == second_value
            ):
                return trimmed_row[value_column]
    return None


def checks_json_has_failed_hard_check(checks_json_path):
    # The uniform contract across every pipeline script: a top-level "checks" array
    # whose records carry severity ("hard"/"soft") and passed (bool). A failed hard
    # check invalidates the stage's output. Returns (has_failure, detail_text).
    checks_report = json.loads(checks_json_path.read_text(encoding="utf-8-sig"))
    for check_record in checks_report.get("checks", []):
        if check_record.get("severity") == "hard" and not check_record.get("passed"):
            return True, check_record.get("check", "unnamed hard check")
    return False, ""


def golden_relative_difference(observed_text, golden_value):
    # Compare a freshly produced cell (a string read from a CSV) against a stored
    # golden number by relative difference, so float formatting like "162056329.0"
    # vs 162056329 compares equal. Returns the relative difference as a float.
    observed_value = float(observed_text)
    golden_number = float(golden_value)
    if golden_number == 0.0:
        return abs(observed_value)
    return abs(observed_value - golden_number) / abs(golden_number)


# =============================================================================
# Fixture staging. Copy the seed fixture gel directory into a fresh temporary
# working tree every run, so stale outputs from a prior run can never mask a
# regression, and so the read-only fixtures are never written to. The manifest is
# copied alongside the gel directory, preserving the "manifest one level above the
# gel dir, relative analysis_path" layout the manifest and aggregator resolve.
# =============================================================================

if not FIXTURES_DIRECTORY.is_dir():
    die("fixtures", "fixtures directory not found: " + str(FIXTURES_DIRECTORY))

seed_gel_directory = FIXTURES_DIRECTORY / FIXTURE_GEL_DIRECTORY_NAME
seed_manifest_path = FIXTURES_DIRECTORY / FIXTURE_MANIFEST_FILENAME
if not seed_gel_directory.is_dir():
    die("fixtures", "seed gel directory not found: " + str(seed_gel_directory))
if not seed_manifest_path.is_file():
    die("fixtures", "seed manifest not found: " + str(seed_manifest_path))

# The gel directory name must end in the analysis suffix, because analyze_gel and
# serve derive gel_id and the expected TIFF stem from it. Asserted, not assumed.
if not seed_gel_directory.name.endswith(GEL_ANALYSIS_DIRECTORY_SUFFIX):
    die(
        "fixtures",
        "fixture gel directory name must end in '"
        + GEL_ANALYSIS_DIRECTORY_SUFFIX
        + "': "
        + seed_gel_directory.name,
    )

# Hash the seed fixtures (their bytes, in sorted path order) so the goldens can
# record which inputs they were captured against. A later run whose fixtures no
# longer hash to this value is told so by cause, before any value comparison, so a
# hand edit to a seed CSV is not misread as a code regression.
fixture_hash_accumulator = hashlib.sha256()
for seed_file_path in sorted(FIXTURES_DIRECTORY.rglob("*")):
    if seed_file_path.is_file():
        relative_name = seed_file_path.relative_to(FIXTURES_DIRECTORY).as_posix()
        fixture_hash_accumulator.update(relative_name.encode("utf-8"))
        fixture_hash_accumulator.update(seed_file_path.read_bytes())
seed_fixtures_hash = fixture_hash_accumulator.hexdigest()

working_root_directory = pathlib.Path(
    tempfile.mkdtemp(prefix="gel_pipeline_regression_")
)
working_gel_directory = working_root_directory / FIXTURE_GEL_DIRECTORY_NAME
shutil.copytree(seed_gel_directory, working_gel_directory)
shutil.copy2(seed_manifest_path, working_root_directory / FIXTURE_MANIFEST_FILENAME)
working_manifest_path = working_root_directory / FIXTURE_MANIFEST_FILENAME
emit_message("fixtures", "staged working tree at " + str(working_root_directory))

# Guard the serve no-crop path: there must be no .tif matching the gel stem beside
# the working gel directory, or serve would rasterise a crop and read an image. The
# temp tree contains only CSVs, so this holds; asserted so a future fixture that
# ships a TIFF cannot silently turn the image path on inside a test.
gel_stem = FIXTURE_GEL_DIRECTORY_NAME[: -len(GEL_ANALYSIS_DIRECTORY_SUFFIX)]
for search_directory in (working_gel_directory, working_root_directory):
    for found_tiff in search_directory.glob("*.tif"):
        if gel_stem in found_tiff.name:
            die(
                "fixtures",
                "a TIFF matching the gel stem is present ("
                + str(found_tiff)
                + "); the serve stage must run the no-crop path with no image read",
            )

# Load the prior goldens (for comparison) or start an empty capture (for --update).
