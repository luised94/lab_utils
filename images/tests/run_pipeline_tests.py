# Shared helpers used by the step blocks below. These are inlined-once utilities
# in spirit, but each is used at every one of the seven step blocks, so by the
# house rule ("add abstraction when the second real call site exists") they are
# real shared helpers, not speculative ones. Kept tiny and side-effect-free.
